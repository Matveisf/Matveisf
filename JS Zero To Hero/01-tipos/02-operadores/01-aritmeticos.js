let a = 5;
let b = 7;

console.log(a + b); // adición
console.log(a - b); // resta
console.log(a * b); // multiplicación
console.log(a / b); // división
console.log(a % b); // módulo o resto


// incrementar
console.log(++a);
console.log(a++);
console.log(a);
// decremento
console.log(--a);
console.log(a--);
console.log(a);